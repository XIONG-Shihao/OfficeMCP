export const tools = Object.freeze(toolDefinitions);
const compiledRegistries = new Map();
export function operationRegistry(toolset = "all") {
  if (compiledRegistries.has(toolset)) return compiledRegistries.get(toolset);
  if (toolset === "full") {
    const compiled = new Map([...operationRegistry("all"), ...operationRegistry("docx-agent")].map(([name, spec]) => [name, Object.freeze({ ...spec, policy: Object.freeze({ ...spec.policy, presets: [...spec.policy.presets, "full"] }) })]));
    compiledRegistries.set(toolset, compiled);
    return compiled;
  }
  const registry = toolset === "docx-agent" ? docxAgentTools : tools;
  const compiled = new Map(
    Object.entries(registry)
      .map(([name, definition]) => defineOperation({ name, ...definition, contract: toolset === "docx-agent" ? "docx/6" : CONTRACT }))
      .filter((spec) => spec.policy.presets.includes(toolset))
      .map((spec) => [spec.name, spec]),
  );
  compiledRegistries.set(toolset, compiled);
  return compiled;
}

export function operationDescriptor(toolset, name) {
  return operationRegistry(toolset).get(name) ?? null;
}

